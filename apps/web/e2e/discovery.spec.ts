test('favourite failure recovers, viewing requests stay requests, and sign-in preserves a room',async({page,context})=>{
  await context.addCookies([{name:'ch-local-test',value:'student',url:'http://127.0.0.1:3100'}]);
  await page.goto(listing,{waitUntil:'domcontentloaded'});
  await page.route('**/api/v1/students/saved-listings',route=>route.fulfill({status:503,json:{message:'Test failure'}}));
  await page.getByRole('button',{name:'Save to favourites'}).first().click();
  await expect(page.getByText('Couldn’t update favourites. Try again.')).toBeVisible();
  await expect(page.getByRole('button',{name:'Save to favourites'}).first()).toHaveAttribute('aria-pressed','false');
  await page.unroute('**/api/v1/students/saved-listings');
  await page.getByRole('button',{name:'Save to favourites'}).first().click();await expect(page.getByRole('button',{name:'Remove from favourites'}).first()).toHaveAttribute('aria-pressed','true');
  await page.getByRole('button',{name:'Request a viewing',exact:true}).click();
  await page.getByRole('textbox',{name:'When would you like to view it, and any questions?'}).fill('Could I view this hostel on Saturday afternoon?');
  const sent=page.waitForRequest(request=>request.url().endsWith('/api/v1/inquiries')&&request.method()==='POST');
  await page.getByRole('button',{name:'Send',exact:true}).click();expect((await sent).postDataJSON().listingId).toBe(listing.split('/').pop());
  await expect(page.getByRole('link',{name:'Contact Us page'})).toHaveAttribute('href','/contact#your-inquiries');
  await context.clearCookies();await page.goto(listing,{waitUntil:'domcontentloaded'});
  await page.getByRole('button',{name:'Select room',exact:true}).first().click();
  const signIn=page.getByRole('link',{name:'Sign in to reserve'}).last();
  const href=await signIn.getAttribute('href');expect(decodeURIComponent(href!)).toContain('room=single-false-500000-1-unknown');expect(decodeURIComponent(href!)).toContain('intent=reserve');
});
